"""Emit supabase/functions/_shared/api/geo_tables.ts from core/geographies.py.

The rail's geography gate had to move server-side (see the retirement of the Pyodide
engine), and its tables are ~400 lines of country lists, region memberships, synonyms and
canonicalisation maps. Hand-copying those into TypeScript is how a typo in one country
name becomes a silently wrong eligibility decision that no reviewer would spot.

So the DATA is generated from the Python that owns it, and only the LOGIC is hand-ported
(supabase/functions/_shared/api/geo_gate.ts, which names the Python symbol it mirrors for
each function). This file is the seam between the two.

What is emitted is the COMPUTED tables, not the source literals: `_REGION_MEMBERS` and the
canonicalisation maps are assembled at import time from several lists plus alias loops, so
dumping the finished dictionaries avoids re-implementing that assembly as well.

    python scripts/gen_geo_tables.py          # rewrites the .ts in place

Re-run it whenever core/geographies.py or auto_scorer's KNOWN_COUNTRIES change.
web/scripts/parity/check-scoring.mjs compares the TS gate against the live Python, so a
stale table shows up as a parity difference rather than as a quiet wrong answer.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from core import geographies as geo            # noqa: E402
from core import type_detect as td             # noqa: E402
import core.auto_scorer as asc                 # noqa: E402

OUT = ROOT / "supabase/functions/_shared/api/geo_tables.ts"
OUT_TYPES = ROOT / "supabase/functions/_shared/api/type_tables.ts"


def js(value) -> str:
    return json.dumps(value, ensure_ascii=False, sort_keys=True)


def main() -> None:
    # Region label (lowercased) → member countries. core/geographies._REGION_MEMBERS.
    region_members = {k: sorted(v) for k, v in sorted(geo._REGION_MEMBERS.items())}

    # Every form the country regex can match, mapped to its canonical short name.
    # Precomputed so the TS never needs canonical_geo's alias/de-inversion machinery:
    # the gate only ever canonicalises a KNOWN_COUNTRIES match.
    country_canon = {c.lower(): geo.canonical_geo(c) for c in asc.KNOWN_COUNTRIES}

    # Longest-first, so "United States" wins over "States" — auto_scorer._COUNTRY_PATTERN.
    known_sorted = sorted(set(asc.KNOWN_COUNTRIES), key=len, reverse=True)

    # auto_scorer._PLACE_TOKENS, longest-first.
    place_tokens = sorted(
        set(geo.COUNTRIES) | set(geo.REGION_TERMS) | set(asc._DEMONYM_TO_PLACE),
        key=len, reverse=True)

    # (variant, region label) pairs, longest variant first — geographies.regions_in_text.
    region_pairs = sorted(
        ((v, term) for term in geo.REGION_TERMS
         for v in geo._region_name_variants(term)),
        key=lambda p: len(p[0]), reverse=True)

    # The development tiers a call can name, by their label+synonym variants only
    # (never their member countries) — auto_scorer._dev_tier_mentioned.
    dev_tier_variants = sorted(
        {v for t in asc._DEV_TIERS for v in geo._region_name_variants(t)},
        key=len, reverse=True)

    body = f'''// GENERATED by scripts/gen_geo_tables.py from core/geographies.py and
// core/auto_scorer.py's KNOWN_COUNTRIES. Do not edit by hand — re-run the script.
//
// These are the COMPUTED tables (memberships and canonicalisation maps are assembled at
// import time in Python), so the TypeScript gate in geo_gate.ts needs no alias-building
// logic of its own. web/scripts/parity/check-scoring.mjs holds the pair together.

/** core/geographies._REGION_MEMBERS — lowercased region label → member countries. */
export const REGION_MEMBERS: Record<string, string[]> = {js(region_members)};

/** Lowercased KNOWN_COUNTRIES form → canonical short name (core/geographies.canonical_geo
 * precomputed over every form auto_scorer._COUNTRY_PATTERN can match). */
export const COUNTRY_CANON: Record<string, string> = {js(country_canon)};

/** core/auto_scorer.KNOWN_COUNTRIES, longest first (so "United States" beats "States"). */
export const KNOWN_COUNTRIES: string[] = {js(known_sorted)};

/** core/auto_scorer._PLACE_TOKENS — countries + region terms + demonyms, longest first. */
export const PLACE_TOKENS: string[] = {js(place_tokens)};

/** core/auto_scorer._DEMONYM_TO_PLACE. */
export const DEMONYM_TO_PLACE: Record<string, string> = {js(asc._DEMONYM_TO_PLACE)};

/** core/geographies.regions_in_text's (variant, region label) pairs, longest variant
 * first so "sub-saharan africa" consumes its span before "africa" can match it. */
export const REGION_VARIANT_PAIRS: [string, string][] = {js([list(p) for p in region_pairs])};

/** core/auto_scorer._DEV_TIERS expanded to label+synonym variants only. */
export const DEV_TIER_VARIANTS: string[] = {js(dev_tier_variants)};

/** core/geographies.INCOME_TIERS — never anchor the org's scope (inclusive keepers). */
export const INCOME_TIERS: string[] = {js(list(geo.INCOME_TIERS))};
'''
    OUT.write_text(body, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(region_members)} regions, "
          f"{len(country_canon)} country forms, {len(region_pairs)} region variants")

    # ── type_detect: the vocabularies the Featured card's exclusion needs ────────
    # The rule lists are ENRICHED at import time (each label's synonyms folded in), so the
    # post-enrichment lists are what gets dumped — same reasoning as the geography maps.
    types_body = f'''// GENERATED by scripts/gen_geo_tables.py from core/type_detect.py.
// Do not edit by hand — re-run the script.
//
// The rule lists are the POST-ENRICHMENT ones (core/type_detect._enrich folds each
// label's synonyms in at import time), so type_detect.ts needs no enrichment logic.

/** core/type_detect._SOLICITATION_RULES — [needle, label], first match wins. */
export const SOLICITATION_RULES: [string, string][] = {js([list(r) for r in td._SOLICITATION_RULES])};

/** core/type_detect._INSTRUMENT_RULES — [needle, label], first match wins. */
export const INSTRUMENT_RULES: [string, string][] = {js([list(r) for r in td._INSTRUMENT_RULES])};

/** core/type_detect.SOLICITATION_GROUPS — index 0 funding calls, 1 EOI/LOI/CfCN,
 * 2 the tender/procurement family. */
export const SOLICITATION_GROUPS: string[][] = {js([sorted(g) for g in td.SOLICITATION_GROUPS])};

/** core/type_detect._PROCUREMENT_HOSTS */
export const PROCUREMENT_HOSTS: string[] = {js(list(td._PROCUREMENT_HOSTS))};

/** core/type_detect._GRANT_PORTAL_HOSTS */
export const GRANT_PORTAL_HOSTS: string[] = {js(list(td._GRANT_PORTAL_HOSTS))};

/** core/type_detect._PROCUREMENT_LABELS */
export const PROCUREMENT_LABELS: string[] = {js(list(td._PROCUREMENT_LABELS))};

/** core/type_detect._CONSULTANCY_LABELS */
export const CONSULTANCY_LABELS: string[] = {js(list(td._CONSULTANCY_LABELS))};

/** core/type_detect._PORTAL_NOISE — [bad, good] replacements. */
export const PORTAL_NOISE: [string, string][] = {js([list(p) for p in td._PORTAL_NOISE])};

/** core/type_detect.OPPORTUNITY_TYPE_EXCLUSIONS — the types this org can never pursue. */
export const OPPORTUNITY_TYPE_EXCLUSION_NAMES: string[] = {js(sorted(td.OPPORTUNITY_TYPE_EXCLUSIONS))};
'''
    OUT_TYPES.write_text(types_body, encoding="utf-8")
    print(f"wrote {OUT_TYPES.relative_to(ROOT)}: {len(td._SOLICITATION_RULES)} solicitation "
          f"rules, {len(td._INSTRUMENT_RULES)} instrument rules")


if __name__ == "__main__":
    main()
