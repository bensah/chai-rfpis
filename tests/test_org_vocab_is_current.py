"""The My Organization page's constant tables must match the Python that owns them.

`supabase/functions/_shared/api/org_vocab.ts` is generated by `scripts/gen_org_vocab.py`
and served to the browser by `GET /organization`. Generated files go stale silently, and
these three go stale expensively:

  * DEFAULT_PROFILE is what a stored profile is MERGED ONTO. A tenant that has never
    opened the editor is shown all of it, and `core.auto_scorer` reads the same merged
    dict — so a missing or changed default means the page describes one organisation by
    another's assumptions.
  * _RENAMED_KEYS is how a profile saved before the 2026 renames is still read. Miss one
    and a field that IS set reads as empty: the completeness bar drops, the page says
    "not yet screening-ready", and nothing on screen explains why.
  * _ORG_DEFAULTS are the identity placeholders that keep a header from rendering blank.
    The page shows them as values, so a reader seeing "Your Organization" is being told
    the real name was never set — which is only true if the placeholder matches.

This compares the emitted tables against the Python's own values rather than re-running
the generator, so it needs no write access and no database.

Run:  python -m unittest tests.test_org_vocab_is_current
"""
import json
import os
import re
import sys
import unittest

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)
os.environ.setdefault("SUPABASE_URL", "https://dummy.supabase.co")
os.environ.setdefault("SUPABASE_KEY", "sb_secret_dummy")

from core import org_profile as op                                   # noqa: E402
from core import settings as st                                      # noqa: E402
from core.program_area_classifier import CATEGORY_FULL               # noqa: E402
from core.program_area_select import RATING_WORD                     # noqa: E402

_TS = os.path.join(_ROOT, "supabase", "functions", "_shared", "api", "org_vocab.ts")


def emitted(name: str):
    """The value of one `export const <name> ... = <json>;` in the generated module."""
    with open(_TS, encoding="utf-8") as f:
        src = f.read()
    m = re.search(r"export const " + re.escape(name) + r"[^=]*= (.+?);\n", src, re.S)
    if not m:
        raise AssertionError(f"{name} is not exported by org_vocab.ts")
    return json.loads(m.group(1))


class GeneratedTablesMatchThePython(unittest.TestCase):
    def test_the_profile_defaults_match(self):
        self.assertEqual(op.DEFAULT_PROFILE, emitted("DEFAULT_PROFILE"),
                         "org_vocab.ts carries different profile defaults than "
                         "core/org_profile.py — re-run scripts/gen_org_vocab.py")

    def test_the_field_order_is_preserved(self):
        """PROFILE_FIELDS is the key order the Python iterates in. It is emitted as a
        list, not inferred from the object, because JSON object order is not a guarantee
        anything should lean on."""
        self.assertEqual(list(op.PROFILE_FIELDS), emitted("PROFILE_FIELDS"))

    def test_every_renamed_key_is_carried(self):
        self.assertEqual(op._RENAMED_KEYS, emitted("RENAMED_KEYS"),
                         "a legacy key missing here reads as an unset field, which drops "
                         "the completeness bar with nothing on screen to explain it")

    def test_a_rename_target_is_a_real_profile_field(self):
        """Every rename must land on a key DEFAULT_PROFILE actually has. One that does not
        would add a field to the merged profile that no default describes and no reader
        asks for."""
        defaults = emitted("DEFAULT_PROFILE")
        for old, new in emitted("RENAMED_KEYS").items():
            with self.subTest(old=old):
                self.assertIn(new, defaults)

    def test_the_identity_placeholders_match(self):
        self.assertEqual(st._ORG_DEFAULTS, emitted("ORG_DEFAULTS"))

    def test_the_label_tables_match(self):
        self.assertEqual(op.LEGAL_TYPE_LABELS, emitted("LEGAL_TYPE_LABELS"))
        self.assertEqual(op.ENTITY_TYPE_LABELS, emitted("ENTITY_TYPE_LABELS"))
        self.assertEqual(list(op.LIST_FIELDS), emitted("LIST_FIELDS"))

    def test_the_rating_words_and_categories_match(self):
        self.assertEqual({str(k): v for k, v in RATING_WORD.items()},
                         emitted("RATING_WORD"))
        self.assertEqual(CATEGORY_FULL, emitted("CATEGORY_FULL"))

    def test_every_rating_score_has_a_word(self):
        """The bar prints "4/5 · High". A score with no word renders "4/5 · " and reads
        like a truncation."""
        words = emitted("RATING_WORD")
        for n in range(0, 6):
            with self.subTest(score=n):
                self.assertTrue(words.get(str(n)))


class NoDeploymentDataIsBakedIn(unittest.TestCase):
    """These are repo constants — the same for every tenant. The VALUES they are merged
    with are read live from the tenant's own row, and none of them belongs in source."""

    def test_no_tenant_name_leaked_into_the_defaults(self):
        with open(_TS, encoding="utf-8") as f:
            src = f.read()
        # The placeholder is deliberately generic; a real organisation's name appearing
        # here would mean somebody generated from a patched constant.
        self.assertIn("Your Organization", src)
        self.assertNotIn("CHAI", src)


if __name__ == "__main__":
    unittest.main()
