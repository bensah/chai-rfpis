"""Settings → Records' per-table specs must match the Python that owns them.

`supabase/functions/_shared/api/records_vocab.ts` is generated by
`scripts/gen_records_vocab.py` from `_DATA_SPECS` in app_pages/admin.py. Every key in
that dict fails SILENTLY when it falls behind, which is why it is a generated table with
a test rather than a hand-written one:

  * `date_cols` decides which columns are parsed as dates for the range filter. A column
    missing here is compared as a string, and a string never falls inside a date range —
    so the filter matches nothing and nothing explains why.
  * `search_cols` decides what a search looks at. A column missing here is visible on
    screen and unfindable by typing: the result is not wrong, it is absent.
  * `edit_fields` decides which columns a save writes. One missing is a field an admin
    can edit in Streamlit and not here; one misspelled is a column that does not exist,
    and the save fails the first time somebody uses it.
  * `order_col` is read with desc=True. A wrong one reorders a long grid, which reads as
    data loss.

Run:  python -m unittest tests.test_records_vocab_is_current
"""
import ast
import json
import os
import re
import sys
import unittest

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)

_TS = os.path.join(_ROOT, "supabase", "functions", "_shared", "api", "records_vocab.ts")
_ADMIN = os.path.join(_ROOT, "app_pages", "admin.py")


def emitted(name: str):
    with open(_TS, encoding="utf-8") as f:
        src = f.read()
    m = re.search(r"export const " + re.escape(name) + r"[^=]*= (.+?);\n", src, re.S)
    if not m:
        raise AssertionError(f"{name} is not exported by records_vocab.ts")
    return json.loads(m.group(1))


def _tree():
    with open(_ADMIN, encoding="utf-8") as f:
        return ast.parse(f.read())


def specs() -> dict:
    for n in ast.walk(_tree()):
        target = n.target if isinstance(n, ast.AnnAssign) else (
            n.targets[0] if isinstance(n, ast.Assign) and len(n.targets) == 1 else None)
        if isinstance(target, ast.Name) and target.id == "_DATA_SPECS" and n.value:
            return ast.literal_eval(n.value)
    raise AssertionError("_DATA_SPECS is no longer a literal in app_pages/admin.py")


def const(name: str):
    for n in ast.walk(_tree()):
        if isinstance(n, ast.Assign):
            for t in n.targets:
                if isinstance(t, ast.Name) and t.id == name:
                    return ast.literal_eval(n.value)
    raise AssertionError(f"{name} is no longer assigned in app_pages/admin.py")


class SpecsMatchTheAdminPage(unittest.TestCase):
    def test_the_same_tables_are_offered(self):
        self.assertEqual(sorted(specs()), sorted(emitted("RECORD_SPECS")))

    def test_the_picker_keeps_the_admin_pages_order(self):
        """Order is the answer, not decoration: the first entry is what the page opens
        on. The spec object itself is emitted with SORTED keys so its diffs stay
        readable, so the order has to be carried separately — deriving the picker from
        that object would put it in alphabetical order instead."""
        self.assertEqual([const("_SCREENED"), const("_EXTRACTED"), *specs()],
                         emitted("RECORD_OPTIONS"))

    def test_every_spec_field_matches(self):
        want, got = specs(), emitted("RECORD_SPECS")
        for name, spec in want.items():
            with self.subTest(table=name):
                g = got[name]
                self.assertEqual(spec["table"], g["table"])
                self.assertEqual(spec["order_col"], g["orderCol"])
                self.assertEqual(list(spec.get("table_cols", [])), g["tableCols"])
                self.assertEqual(dict(spec.get("col_labels", {})), g["colLabels"])
                self.assertEqual(list(spec.get("date_cols", [])), g["dateCols"])
                self.assertEqual(list(spec.get("search_cols", [])), g["searchCols"])
                self.assertEqual(list(spec.get("advanced_filters", [])),
                                 g["advancedFilters"])
                self.assertEqual([list(f) for f in spec.get("edit_fields", [])],
                                 g["editFields"])
                self.assertEqual(spec.get("caption", ""), g["caption"])

    def test_every_optional_key_is_present(self):
        """A missing key is `undefined` in TypeScript, and `undefined.includes(...)`
        throws inside a render. The absence is resolved once, in the generator."""
        for name, g in emitted("RECORD_SPECS").items():
            with self.subTest(table=name):
                for key in ("tableCols", "colLabels", "dateCols", "searchCols",
                            "advancedFilters", "editFields", "caption"):
                    self.assertIn(key, g)

    def test_the_extracted_columns_match_their_branch(self):
        self.assertEqual(const("_show_cols"), emitted("EXTRACTED_COLUMNS"))


class TheSpecsAreInternallyCoherent(unittest.TestCase):
    """Checks that would catch a bad spec in admin.py ITSELF, not only a stale copy."""

    def test_every_searched_column_is_a_column_the_table_has(self):
        """A searched column must EXIST; it need not be on the grid.

        Searching something the grid does not show is deliberate here and worth keeping:
        `applied_funding.remarks` and `engagement_logs.outcome` are long free-text fields
        that would swamp a row, and they are exactly what somebody types to find a
        record. What must not happen is searching a column that is not there — PostgREST
        answers 400 and the whole grid fails to load.
        """
        for name, g in emitted("RECORD_SPECS").items():
            known = set(g["tableCols"]) | {f[0] for f in g["editFields"]}
            for col in g["searchCols"]:
                with self.subTest(table=name, column=col):
                    self.assertIn(col, known)

    def test_every_filtered_column_is_a_column_the_table_has(self):
        """A dropdown filter builds its options from the rows, so an absent column gives
        an always-empty dropdown that silently filters everything out when used."""
        for name, g in emitted("RECORD_SPECS").items():
            known = set(g["tableCols"]) | {f[0] for f in g["editFields"]}
            for col in g["advancedFilters"]:
                with self.subTest(table=name, column=col):
                    self.assertIn(col, known)

    def test_the_order_column_is_one_of_the_tables_own(self):
        """It is read with desc=True straight from PostgREST. A column that is not there
        is a 400 on the first load of that table, not a quiet mis-sort."""
        for name, g in emitted("RECORD_SPECS").items():
            with self.subTest(table=name):
                known = set(g["tableCols"]) | {f[0] for f in g["editFields"]}
                self.assertIn(g["orderCol"], known)

    #: The control kinds the editor renders. `bool` is the one that is easy to miss —
    #: only `meeting_logs.is_resolved` uses it, and a renderer that handled the other
    #: three would drop the Resolved checkbox out of the dialog with no error anywhere.
    KINDS = {"date", "text", "area", "bool"}

    def test_every_edit_field_has_a_kind_the_renderer_knows(self):
        """`kind` picks the control. An unknown one renders as nothing at all, and the
        field silently drops out of the dialog — a field an admin cannot set, with no
        message to say so."""
        for name, g in emitted("RECORD_SPECS").items():
            for col, kind, _label in g["editFields"]:
                with self.subTest(table=name, column=col):
                    self.assertIn(kind, self.KINDS)

    def test_the_renderer_handles_every_kind_the_specs_use(self):
        """The other direction, and the one that catches a NEW kind added in admin.py:
        every kind in use must be one this test's own list names, so adding a fifth
        fails here rather than in a browser."""
        used = {kind for g in emitted("RECORD_SPECS").values()
                for _c, kind, _l in g["editFields"]}
        self.assertTrue(used <= self.KINDS,
                        f"records_vocab uses kinds the editor does not render: "
                        f"{sorted(used - self.KINDS)}")

    def test_a_date_column_is_edited_as_a_date(self):
        """A date column offered as a text box lets somebody type anything into it, and
        the range filter then skips the row for good."""
        for name, g in emitted("RECORD_SPECS").items():
            kinds = {col: kind for col, kind, _ in g["editFields"]}
            for col in g["dateCols"]:
                if col in kinds:
                    with self.subTest(table=name, column=col):
                        self.assertEqual("date", kinds[col])


if __name__ == "__main__":
    unittest.main()
