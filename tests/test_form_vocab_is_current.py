"""The RFP editor's dropdowns must offer what the Python recognises.

`supabase/functions/_shared/api/form_vocab.ts` is generated by
`scripts/gen_form_vocab.py` from config/dropdowns.yaml and four core modules, and then
served to the browser by `GET /pipelines/form-options`. Generated files go stale silently:
somebody adds a stage to the YAML, nobody re-runs the script, and the React editor quietly
stops offering it while the Streamlit one does.

That is not cosmetic. These are CONTROLLED vocabularies with consequences —
`decision` decides who appears in Track and whether the scan tombstones a row,
`opportunity_type` decides whether the eligibility gate rejects the call outright — so a
dropdown that has fallen behind writes rows the rest of the app reads differently from
the person who typed them.

This compares the emitted lists against the Python's own values rather than re-running the
generator, so it needs no write access and no database: the guarantee wanted is "the .ts
agrees with the Python", which is exactly what is checked.

Run:  python -m unittest tests.test_form_vocab_is_current
"""
import json
import os
import re
import sys
import unittest

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
if _ROOT not in sys.path:
    sys.path.insert(0, _ROOT)
os.environ.setdefault("SUPABASE_URL", "https://dummy.supabase.co")
os.environ.setdefault("SUPABASE_KEY", "sb_secret_dummy")

from core import dropdowns                                    # noqa: E402
from core import type_detect as td                            # noqa: E402
from core.scorer import CRITERIA, CRITERION_RESPONSES         # noqa: E402

_TS = os.path.join(_ROOT, "supabase", "functions", "_shared", "api", "form_vocab.ts")
# The keys gen_form_vocab.py emits, which is also the set the editor's tabs read.
PLAIN_KEYS = [
    "applicant_role", "funding_window", "time_to_award", "submission_format",
    "feasibility", "decisions", "stages", "progress_status", "donor_decision",
    "support_roles", "eligibility_values", "report_statuses", "report_types",
]


def emitted(name: str):
    """The value of one `export const <name> ... = <json>;` in the generated module."""
    with open(_TS, encoding="utf-8") as f:
        src = f.read()
    m = re.search(r"export const " + re.escape(name) + r"[^=]*= (.+?);\n", src, re.S)
    if not m:
        raise AssertionError(f"{name} is not exported by form_vocab.ts")
    return json.loads(m.group(1))


class GeneratedListsMatchThePython(unittest.TestCase):
    def test_the_plain_lists_match_dropdowns_yaml(self):
        got = emitted("DROPDOWNS")
        self.assertEqual(sorted(PLAIN_KEYS), sorted(got),
                         "form_vocab.ts offers a different set of lists than the "
                         "generator emits — re-run scripts/gen_form_vocab.py")
        for key in PLAIN_KEYS:
            with self.subTest(key=key):
                self.assertEqual(list(dropdowns.get(key) or []), got[key])

    def test_stage_order_is_preserved(self):
        """ORDER IS THE MEANING for stages: the Bidding progress bar reads left to right,
        so a reordered list silently redraws what "further along" means."""
        self.assertEqual(list(dropdowns.get("stages") or []), emitted("DROPDOWNS")["stages"])

    def test_programme_areas_and_geographies_come_from_the_canonical_modules(self):
        # dropdowns.get routes both of these away from the YAML on purpose; the generated
        # file must have gone the same way, or the editor offers a stale YAML copy.
        self.assertEqual(list(dropdowns.get("call_domain_areas") or []),
                         emitted("PROGRAM_AREAS"))
        self.assertEqual(list(dropdowns.get("call_geographic_scope") or []),
                         emitted("GEO_OPTIONS"))

    def test_every_criterion_offers_its_own_rich_answers(self):
        got = emitted("CRITERION_ANSWERS")
        self.assertEqual(sorted(CRITERIA), sorted(got),
                         "one of the nine criteria has no answers in form_vocab.ts")
        for key in CRITERIA:
            with self.subTest(criterion=key):
                self.assertEqual(list(CRITERION_RESPONSES.get(key) or []), got[key])
                self.assertTrue(got[key], f"{key} would render an empty dropdown")

    def test_the_three_type_axes_match_type_detect(self):
        self.assertEqual(list(td.OPPORTUNITY_TYPES), emitted("OPPORTUNITY_TYPES"))
        self.assertEqual(list(td.SOLICITATION_TYPES), emitted("SOLICITATION_TYPES"))
        self.assertEqual(list(td.INSTRUMENT_TYPES), emitted("INSTRUMENT_TYPES"))

    def test_the_gates_exclusions_are_all_offerable(self):
        """A row can only be classified as something the dropdown offers, and the
        eligibility gate's own exclusion classes must be among them — otherwise a reviewer
        cannot mark a call as the Procurement it is."""
        for name in td.OPPORTUNITY_TYPE_EXCLUSIONS:
            with self.subTest(name=name):
                self.assertIn(name, emitted("OPPORTUNITY_TYPES"))


class NoDeploymentDataIsBakedIn(unittest.TestCase):
    """`team_members` and `currencies` are overlaid from app_settings by
    core/dropdowns.load, and the roster is deliberately absent from the repo — real names
    are configured per deployment. Generating either would publish one organisation's
    staff, or ship the YAML's "Team Member 1..N" placeholders as if they were people."""

    def test_the_roster_is_not_emitted(self):
        self.assertNotIn("team_members", emitted("DROPDOWNS"))

    def test_the_currency_table_is_not_emitted(self):
        self.assertNotIn("currencies", emitted("DROPDOWNS"))

    def test_no_yaml_placeholder_name_leaked_into_any_list(self):
        with open(_TS, encoding="utf-8") as f:
            src = f.read()
        self.assertNotIn("Team Member", src)


if __name__ == "__main__":
    unittest.main()
